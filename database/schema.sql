ALTER TABLE movies ENABLE ROW LEVEL SECURITY;
ALTER TABLE theatres ENABLE ROW LEVEL SECURITY;
ALTER TABLE showtimes ENABLE ROW LEVEL SECURITY;
ALTER TABLE seats ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking_seats ENABLE ROW LEVEL SECURITY;
ALTER TABLE seat_reservations ENABLE ROW LEVEL SECURITY;

CREATE POLICY "public read movies" ON movies FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "public read theatres" ON theatres FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "public read showtimes" ON showtimes FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "public read seats" ON seats FOR SELECT TO anon, authenticated USING (true);
